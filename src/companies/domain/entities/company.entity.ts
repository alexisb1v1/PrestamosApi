export class Company {
  id?: string; // Auto-generated by database
  companyName: string;
  status: string;
  createdAt: Date;

  label?: string;
  subdomain?: string;
  keyToken?: string;
  settings?: Record<string, any>;
  initialCapital?: number | null;
  isDemo?: boolean;

  constructor(
    companyName: string,
    status: string,
    createdAt: Date,
    id?: string,
    label?: string,
    subdomain?: string,
    keyToken?: string,
    settings?: Record<string, any>,
    isDemo?: boolean,
    initialCapital?: number | null,
  ) {
    this.id = id;
    this.companyName = companyName;
    this.status = status;
    this.createdAt = createdAt;
    this.label = label;
    this.subdomain = subdomain;
    this.keyToken = keyToken;
    this.settings = settings || {};
    this.isDemo = isDemo ?? false;
    this.initialCapital = initialCapital !== undefined ? (initialCapital !== null ? Number(initialCapital) : null) : null;
  }

  getNormalizedStatus(): string {
    const rawStatus = this.status;
    if (rawStatus === 'ACTIVO') return 'ACTIVE';
    if (rawStatus === 'INACTIVO') return 'INACTIVE';
    if (rawStatus === 'SUSPENDIDO') return 'SUSPENDED';
    return rawStatus;
  }
}
